"""
Neural Network Training for Element Identification

This script:
1. Generates synthetic spectra via SyntheticLIBSDataset (Sample_bootstrap.py)
2. Loads multi-weight spectra from element_weights/multi_weights.h5
   (generated by weight_generator.py: 100 TE/NE combos x 77 elements = 7700 rows)
3. Performs matrix multiplication: spectra @ weights.T  -> (n_samples, 7700)
4. Reduces 7700 features to 77 via a trainable projection matrix (optimized during training)
5. Feeds the 77 projected features into a FC hidden layer
6. Predicts element presence (0-1) for all 77 elements

Architecture:
    spectra @ weight_spectra.T -> (n, 7700) @ W_proj -> (n, 77) -> Hidden -> Output (77)
    W_proj is randomly initialized and learned jointly with the NN weights.

Prerequisite:
    Run weight_generator.py first to generate element_weights/multi_weights.h5

Uses PyTorch if available, otherwise falls back to optimized NumPy.
"""

