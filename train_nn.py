if USE_TORCH:
    class ElementIdentificationNN(nn.Module):
        """
        NN with trainable projection: n_features -> n_elements -> hidden -> n_outputs.
        
        The projection layer reduces 7700 features to 77 (one per element)
        via a learned weight matrix, then feeds into a FC hidden layer.
        """
        
        def __init__(self, n_features, n_elements, n_hidden, n_outputs, dropout=0.2):
            super(ElementIdentificationNN, self).__init__()
            # Learnable projection: (batch, 7700) -> (batch, 77)
            self.projection = nn.Linear(n_features, n_elements, bias=False)
            # FC network on the projected features
            self.network = nn.Sequential(
                nn.Linear(n_elements, n_hidden),
                nn.BatchNorm1d(n_hidden),
                nn.ReLU(),
                nn.Dropout(dropout),
                nn.Linear(n_hidden, n_outputs),
                nn.Sigmoid()
            )
        
        def forward(self, x):
            x = self.projection(x)
            return self.network(x)

    def train_torch(model, train_loader, val_loader, epochs):
        """Train using PyTorch."""
        criterion = nn.BCELoss()
        optimizer = optim.Adam(model.parameters(), lr=LEARNING_RATE, weight_decay=1e-5)
        scheduler = optim.lr_scheduler.ReduceLROnPlateau(optimizer, 'min', factor=0.5, patience=30)
        
        history = {'train_loss': [], 'val_loss': [], 'train_acc': [], 'val_acc': []}
        best_val_loss = float('inf')
        best_state = None
        
        print(f"\nTraining with PyTorch on {device}...")
        print("-" * 70)
        
        for epoch in range(epochs):
            model.train()
            train_loss, train_correct, train_total = 0.0, 0, 0
            for inputs, targets in train_loader:
                inputs, targets = inputs.to(device), targets.to(device)
                optimizer.zero_grad()
                outputs = model(inputs)
                loss = criterion(outputs, targets)
                loss.backward()
                optimizer.step()
                train_loss += loss.item()
                train_correct += ((outputs > 0.5).float() == targets).sum().item()
                train_total += targets.numel()
            
            model.eval()
            val_loss, val_correct, val_total = 0.0, 0, 0
            with torch.no_grad():
                for inputs, targets in val_loader:
                    inputs, targets = inputs.to(device), targets.to(device)
                    outputs = model(inputs)
                    val_loss += criterion(outputs, targets).item()
                    val_correct += ((outputs > 0.5).float() == targets).sum().item()
                    val_total += targets.numel()
            
            train_loss /= len(train_loader)
            val_loss /= len(val_loader)
            train_acc = train_correct / train_total
            val_acc = val_correct / val_total
            
            scheduler.step(val_loss)
            if val_loss < best_val_loss:
                best_val_loss = val_loss
                best_state = model.state_dict().copy()
            
            history['train_loss'].append(train_loss)
            history['val_loss'].append(val_loss)
            history['train_acc'].append(train_acc)
            history['val_acc'].append(val_acc)
            
            if (epoch + 1) % 100 == 0 or epoch == 0:
                print(f"Epoch {epoch+1:4d}/{epochs}: "
                      f"Train Loss: {train_loss:.4f}, Acc: {train_acc:.4f} | "
                      f"Val Loss: {val_loss:.4f}, Acc: {val_acc:.4f}")
        
        if best_state:
            model.load_state_dict(best_state)
        print("-" * 70)
        return history


