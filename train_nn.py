def sigmoid(x):
    x = np.clip(x, -500, 500)
    return np.where(x >= 0, 1 / (1 + np.exp(-x)), np.exp(x) / (1 + np.exp(x)))

def relu(x):
    return np.maximum(0, x)

def relu_derivative(x):
    return (x > 0).astype(float)

def bce_loss(y_pred, y_true, eps=1e-7):
    y_pred = np.clip(y_pred, eps, 1 - eps)
    return -np.mean(y_true * np.log(y_pred) + (1 - y_true) * np.log(1 - y_pred))


class NumpyNN:
    """
    NN with trainable projection implemented in NumPy.
    
    Architecture: projection (n_features -> n_elements) -> hidden -> output
    The projection layer is a learned weight matrix (no bias).
    """
    
    def __init__(self, n_features, n_elements, n_hidden, n_outputs):
        # Projection layer: (batch, 7700) -> (batch, 77)
        self.W0 = np.random.randn(n_features, n_elements) * np.sqrt(2.0 / n_features)
        # Hidden layer: (batch, 77) -> (batch, n_hidden)
        self.W1 = np.random.randn(n_elements, n_hidden) * np.sqrt(2.0 / n_elements)
        self.b1 = np.zeros((1, n_hidden))
        # Output layer: (batch, n_hidden) -> (batch, n_outputs)
        self.W2 = np.random.randn(n_hidden, n_outputs) * np.sqrt(2.0 / n_hidden)
        self.b2 = np.zeros((1, n_outputs))
        self.cache = {}
    
    def forward(self, X):
        self.cache['X'] = X
        self.cache['P'] = X @ self.W0                       # projection
        self.cache['Z1'] = self.cache['P'] @ self.W1 + self.b1
        self.cache['A1'] = relu(self.cache['Z1'])
        self.cache['Z2'] = self.cache['A1'] @ self.W2 + self.b2
        self.cache['A2'] = sigmoid(self.cache['Z2'])
        return self.cache['A2']
    
    def backward(self, X, y, lr, clip=1.0):
        n = X.shape[0]
        # Output layer gradients
        dZ2 = self.cache['A2'] - y
        dW2 = np.clip(self.cache['A1'].T @ dZ2 / n, -clip, clip)
        db2 = np.clip(np.mean(dZ2, axis=0, keepdims=True), -clip, clip)
        # Hidden layer gradients
        dZ1 = (dZ2 @ self.W2.T) * relu_derivative(self.cache['Z1'])
        dW1 = np.clip(self.cache['P'].T @ dZ1 / n, -clip, clip)
        db1 = np.clip(np.mean(dZ1, axis=0, keepdims=True), -clip, clip)
        # Projection layer gradients
        dP = dZ1 @ self.W1.T
        dW0 = np.clip(self.cache['X'].T @ dP / n, -clip, clip)
        # Update all weights
        self.W2 -= lr * np.nan_to_num(dW2)
        self.b2 -= lr * np.nan_to_num(db2)
        self.W1 -= lr * np.nan_to_num(dW1)
        self.b1 -= lr * np.nan_to_num(db1)
        self.W0 -= lr * np.nan_to_num(dW0)


def train_numpy(model, X_train, y_train, X_val, y_val, epochs, lr):
    """Train using NumPy."""
    history = {'train_loss': [], 'val_loss': [], 'train_acc': [], 'val_acc': []}
    print("\nTraining with NumPy...")
    print("-" * 70)
    for epoch in range(epochs):
        train_pred = model.forward(X_train)
        model.backward(X_train, y_train, lr)
        train_loss = bce_loss(train_pred, y_train)
        train_acc = ((train_pred > 0.5) == y_train).mean()
        val_pred = model.forward(X_val)
        val_loss = bce_loss(val_pred, y_val)
        val_acc = ((val_pred > 0.5) == y_val).mean()
        history['train_loss'].append(train_loss)
        history['val_loss'].append(val_loss)
        history['train_acc'].append(train_acc)
        history['val_acc'].append(val_acc)
        if (epoch + 1) % 100 == 0 or epoch == 0:
            print(f"Epoch {epoch+1:4d}/{epochs}: "
                  f"Train Loss: {train_loss:.4f}, Acc: {train_acc:.4f} | "
                  f"Val Loss: {val_loss:.4f}, Acc: {val_acc:.4f}")
    print("-" * 70)
    return history


